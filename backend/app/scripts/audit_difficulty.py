"""Phase 0 difficulty audit: hand-assigned levels vs a word-norm estimate.

    uv run python -m app.scripts.audit_difficulty [--write]

Reports the rank correlation between the catalogue's difficulty and the estimate from
app.exercises.norms, and lists pictures where the two differ by two or more levels. Those
are candidates for clinician review; nothing in the catalogue is changed automatically.
"""

import sys
from pathlib import Path

from app.exercises.catalog import load_catalog
from app.exercises.norms import estimate_levels
from app.validation.metrics import spearman

REPORT = Path(__file__).parents[3] / "docs" / "validation" / "results" / "difficulty.md"


def naming_items() -> list[dict]:
    catalog = load_catalog()
    return [p for p in catalog.get("photos", []) if "picture_naming" in p["exercise_types"]]


def agreement(item: dict) -> str:
    norms = item.get("norms")
    return f"{norms['name_agreement']:.0%}" if norms else "—"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    items = naming_items()
    est = estimate_levels([i["target"] for i in items])
    hand = [i["difficulty"] for i in items]
    norm = [est[i["target"]][1] for i in items]
    rho_all = spearman(hand, norm)
    # BOSS name agreement: lower agreement predicts harder naming (Nickels & Howard 1995).
    normed = [i for i in items if i.get("norms")]
    rho_agreement = spearman(
        [i["difficulty"] for i in normed], [-i["norms"]["name_agreement"] for i in normed]
    )
    flagged = sorted(
        (i for i in items if abs(i["difficulty"] - est[i["target"]][1]) >= 2),
        key=lambda i: -abs(i["difficulty"] - est[i["target"]][1]),
    )
    lines = [
        "# Difficulty audit: results",
        "",
        "Generated by `uv run python -m app.scripts.audit_difficulty --write`. "
        "Method and limits: [difficulty.md](../difficulty.md).",
        "",
        f"{len(items)} picture-naming items ({len(est)} distinct target words).",
        "",
        "| Catalogue level compared with | Items | Spearman ρ |",
        "|---|---|---|",
        f"| Word frequency and length (norm level) | {len(items)} | {rho_all:.2f} |",
        f"| BOSS name agreement (reversed: lower agreement = harder) | {len(normed)} "
        f"| {rho_agreement:.2f} |",
        "",
        f"## Items to review ({len(flagged)}: levels differ by 2 or more)",
        "",
        "| Picture | Name agreement | Target | Zipf frequency | Syllables | Catalogue level "
        "| Norm level |",
        "|---|---|---|---|---|---|---|",
    ]
    for i in flagged:
        w, level = est[i["target"]]
        lines.append(
            f"| {i['slug']} | {agreement(i)} | {i['target']} | {w.zipf:.2f} | {w.syllables} | "
            f"{i['difficulty']} | {level} |"
        )
    lines += [
        "",
        "## All target words",
        "",
        "| Target | Zipf frequency | Syllables | Norm level | Catalogue levels |",
        "|---|---|---|---|---|",
    ]
    for target, (w, level) in sorted(est.items(), key=lambda kv: (kv[1][1], kv[0])):
        cat = sorted({i["difficulty"] for i in items if i["target"] == target})
        lines.append(
            f"| {target} | {w.zipf:.2f} | {w.syllables} | {level} | {', '.join(map(str, cat))} |"
        )
    report = "\n".join(lines) + "\n"
    print(report)
    if "--write" in sys.argv:
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
