"""Prompt study: does each prompt-engineering step actually change what the model produces?

    uv run python -m app.scripts.prompt_study --split dev [--arms naive,v1,v2] [--repeats 3]
    uv run python -m app.scripts.prompt_study --split test --write

Sends the same exercise requests to the local model under each prompt ("arm") and puts every
output through the production validators, with the app's two-attempt retry:

  naive-noschema  one-line prompt, free text
  naive           one-line prompt, JSON Schema enforced
  v1              exercise_generation_v1: role, context, constraints, safety, type-specific rules
  v2              production: v1 plus supplied facts, contrastive examples, a final check and
                  a schema that limits the picture to the candidates

Pictures are split in two by a hash of their slug. Prompts are revised while looking at `dev`
only; `test` is run once at the end, so the reported result is not tuned to its own pictures.
No database and no patient data are involved. Validators check form and safety, not meaning.
"""

import argparse
import asyncio
import hashlib
import json
import math
import random
import sys
from collections import Counter
from dataclasses import replace
from pathlib import Path
from statistics import median

from app.ai import personalization
from app.ai.ollama import OllamaAIProvider
from app.ai.prompt_archive import naive_prompts, v1_prompts
from app.ai.prompts import EXERCISE_PROMPT_VERSION, exercise_prompts
from app.core.config import get_settings
from app.scripts.genai_audit import (
    CANDIDATES,
    TYPES,
    exercise_input,
    generate,
    stimuli,
    validate_exercise,
)

RESULTS = Path(__file__).parents[3] / "docs" / "validation" / "results"
ARMS = {
    "naive-noschema": naive_prompts,
    "naive": naive_prompts,
    "v1": v1_prompts,
    "v2": exercise_prompts,
}
# Wording from the prompt's own examples: accepted, but copied rather than written for the word.
EXAMPLE_PHRASES = ("pour tea or coffee", "who is doing it", "say who you can see")


def in_split(slug: str, split: str) -> bool:
    digit = int(hashlib.sha256(slug.encode()).hexdigest(), 16) % 2
    return digit == (0 if split == "dev" else 1)


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% confidence interval for a proportion."""
    if not n:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    mid = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, mid - half), min(1.0, mid + half)


def jobs(split: str, repeats: int, seed: int) -> list[tuple]:
    rng = random.Random(seed)
    all_stims = stimuli()
    out = []
    for kind in TYPES:
        eligible = [x for x in all_stims if kind in x.exercise_types]
        for stim in eligible:
            if not in_split(stim.slug, split):
                continue
            same = [x for x in eligible if x.difficulty == stim.difficulty and x is not stim]
            pool = [stim, *rng.sample(same, min(CANDIDATES - 1, len(same)))]
            out += [(kind, stim, pool, r) for r in range(repeats)]
    return out


async def run_arm(arm: str, job_list: list[tuple]) -> list[dict]:
    s = get_settings()
    provider = OllamaAIProvider(s.ollama_base_url, s.ollama_model, timeout_s=120)
    out = []
    for i, (kind, stim, pool, r) in enumerate(job_list, 1):
        inp = exercise_input(kind, stim, pool)
        system, user = ARMS[arm](inp)
        req = replace(personalization.build_request(inp), system_prompt=system, user_prompt=user)
        if arm == "naive-noschema":
            req = replace(req, output_schema=None)
        elif arm != "v2":  # earlier prompts ran with the schema that did not limit the slug
            req = replace(req, output_schema=personalization.exercise_schema(kind))
        pool_map = {x.slug: x for x in pool}
        records = await generate(
            provider, req, lambda raw, k=kind, p=pool_map: validate_exercise(raw, k, p)
        )
        out.append(
            {"arm": arm, "exercise_type": kind, "slug": stim.slug, "repeat": r, "attempts": records}
        )
        if i % 25 == 0:
            print(f"{arm} {i}/{len(job_list)}", file=sys.stderr, flush=True)
    return out


def _pct(k: int, n: int) -> str:
    low, high = wilson(k, n)
    return f"{100 * k / n:.0f}% ({100 * low:.0f}-{100 * high:.0f})" if n else "n/a"


def _copied(attempts: list[dict]) -> bool:
    last = attempts[-1]
    if last["status"] != "accepted":
        return False
    text = json.dumps(last.get("parsed") or {}).lower()
    return any(p in text for p in EXAMPLE_PHRASES)


def summarise(results: list[dict], split: str, arms: list[str]) -> str:
    s = get_settings()
    lines = [
        "# Prompt study: results",
        "",
        f"Generated by `app.scripts.prompt_study`. Model `{s.ollama_model}`, split `{split}`, "
        f"production prompt `{EXERCISE_PROMPT_VERSION}`. Method: "
        "[prompt-engineering.md](../../prompt-engineering.md). Brackets are 95% confidence "
        "intervals. Validators check form and safety, not whether a cue is true.",
        "",
        "## Valid output per request",
        "",
        "| Prompt | Requests | Valid first time | Valid after retry | Median latency |",
        "|---|---|---|---|---|",
    ]
    for arm in arms:
        rows = [r for r in results if r["arm"] == arm]
        first = sum(r["attempts"][0]["status"] == "accepted" for r in rows)
        final = sum(r["attempts"][-1]["status"] == "accepted" for r in rows)
        ms = [a["ms"] for r in rows for a in r["attempts"]]
        lat = f"{median(ms) / 1000:.1f} s" if ms else "n/a"
        lines.append(
            f"| {arm} | {len(rows)} | {_pct(first, len(rows))} | {_pct(final, len(rows))} | {lat} |"
        )
    lines += ["", "## Valid first time, by exercise type", ""]
    lines += ["| Prompt | " + " | ".join(TYPES) + " |", "|---|" + "---|" * len(TYPES)]
    for arm in arms:
        cells = []
        for kind in TYPES:
            rows = [r for r in results if r["arm"] == arm and r["exercise_type"] == kind]
            cells.append(
                _pct(sum(r["attempts"][0]["status"] == "accepted" for r in rows), len(rows))
            )
        lines.append(f"| {arm} | " + " | ".join(cells) + " |")
    lines += ["", "## Why outputs were rejected (share of raw outputs)", ""]
    reasons: dict[str, Counter] = {arm: Counter() for arm in arms}
    totals = Counter()
    for r in results:
        for a in r["attempts"]:
            totals[r["arm"]] += 1
            for reason in a.get("reasons") or []:
                reasons[r["arm"]][reason.split(":")[0]] += 1
    codes = sorted({c for counter in reasons.values() for c in counter})
    lines += ["| Reason | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    for code in codes:
        cells = [f"{100 * reasons[arm][code] / max(totals[arm], 1):.1f}%" for arm in arms]
        lines.append(f"| `{code}` | " + " | ".join(cells) + " |")
    lines += ["", "## Accepted outputs that copied the prompt's example", ""]
    lines += ["| Prompt | Copied | Accepted |", "|---|---|---|"]
    for arm in arms:
        rows = [r for r in results if r["arm"] == arm and r["attempts"][-1]["status"] == "accepted"]
        lines.append(f"| {arm} | {sum(_copied(r['attempts']) for r in rows)} | {len(rows)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", choices=["dev", "test"], default="dev")
    parser.add_argument("--arms", default="naive-noschema,naive,v1,v2")
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    arms = args.arms.split(",")
    job_list = jobs(args.split, args.repeats, args.seed)
    print(f"{len(job_list)} requests per arm", file=sys.stderr, flush=True)
    results = []
    for arm in arms:
        results += asyncio.run(run_arm(arm, job_list))
    report = summarise(results, args.split, arms)
    print(report)
    if args.write:
        (RESULTS / "prompt-study.md").write_text(report, encoding="utf-8")
        with (RESULTS / "prompt-study.jsonl").open("w", encoding="utf-8") as f:
            for r in results:
                f.write(json.dumps(r) + "\n")


if __name__ == "__main__":
    main()
